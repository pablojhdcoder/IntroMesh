import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { extraEventParticipations } from "../src/domain/demo-community";
import { EXTRA_EVENTS } from "../src/lib/store/types";

function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

async function main() {
  const now = Date.parse("2026-11-04T09:00:00.000Z");
  const rows = extraEventParticipations(
    EXTRA_EVENTS.map((event) => event.id),
    8,
    now,
  );
  const values = rows
    .map(
      (record) =>
        `  (${sqlString(record.userId)}, ${sqlString(record.eventId)}, '', '{}'::text[], '{}'::text[], 0, ${sqlString(record.inputHash)}, true, 'discoverable', 'joined', now(), now(), 'attendee', null)`,
    )
    .join(",\n");

  const sql = `-- Demo members for every extra room: 8 joined fixtures each.
-- Idempotent: safe to re-apply. Generated by scripts/emit-event-demos.ts
-- from src/domain/demo-community.ts (same roster as npm run seed:supabase).

insert into event_participations (user_id, event_id, intent_text, looking_for, collaboration_interests, revision, input_hash, consent, visibility, status, updated_at, joined_at, role, last_active_at)
values
${values}
on conflict (user_id, event_id) do update set
  status = 'joined',
  consent = true,
  visibility = 'discoverable',
  updated_at = excluded.updated_at,
  joined_at = excluded.joined_at;
`;

  const target = path.join(process.cwd(), "supabase", "migrations", "0015_event_demo_participations.sql");
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, sql, "utf8");
  process.stdout.write(`${target}\n${rows.length} participaciones en ${EXTRA_EVENTS.length} eventos\n`);
}

void main();
